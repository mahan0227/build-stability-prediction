from __future__ import annotations

import argparse
import re
import textwrap
from pathlib import Path

from fpdf import FPDF


class PDF(FPDF):
    def header(self) -> None:
        self.set_font("Times", "I", 9)
        self.cell(0, 6, "Objective 1 Paper Pack", new_x="LMARGIN", new_y="NEXT", align="R")

    def footer(self) -> None:
        self.set_y(-12)
        self.set_font("Times", "I", 9)
        self.cell(0, 8, f"Page {self.page_no()}", align="C")


def _write_wrapped(pdf: PDF, line: str, size: int = 11, style: str = "") -> None:
    pdf.set_font("Times", style, size)
    clean = "".join(ch if 31 < ord(ch) < 127 else " " for ch in line)
    wrapped = textwrap.wrap(clean, width=110, break_long_words=True, replace_whitespace=False) or [""]
    for w in wrapped:
        if pdf.get_y() > 272:
            pdf.add_page()
        pdf.cell(0, 6, w, new_x="LMARGIN", new_y="NEXT")


def main() -> None:
    parser = argparse.ArgumentParser(description="Export Objective 1 paper pack markdown to PDF.")
    parser.add_argument(
        "--md",
        default="outputs/objective1/paper_pack/objective1_results_section.md",
        help="Input markdown file generated by paper pack pipeline.",
    )
    parser.add_argument(
        "--pdf",
        default="outputs/objective1/paper_pack/objective1_results_section.pdf",
        help="Output PDF path.",
    )
    parser.add_argument(
        "--figure",
        default="outputs/objective1/paper_pack/figures/association_plot.png",
        help="Optional figure to embed in PDF.",
    )
    args = parser.parse_args()

    md_path = Path(args.md)
    pdf_path = Path(args.pdf)
    fig_path = Path(args.figure)
    pdf_path.parent.mkdir(parents=True, exist_ok=True)

    if not md_path.exists():
        raise FileNotFoundError(f"Markdown not found: {md_path}")

    text = md_path.read_text(encoding="utf-8")
    pdf = PDF(format="A4")
    pdf.set_auto_page_break(auto=True, margin=16)
    pdf.add_page()

    for raw in text.splitlines():
        line = re.sub(r"`([^`]+)`", r"\1", raw)
        line = re.sub(r"\*\*(.*?)\*\*", r"\1", line)
        if line.startswith("# "):
            _write_wrapped(pdf, line[2:].strip(), size=17, style="B")
            pdf.ln(1)
        elif line.startswith("## "):
            _write_wrapped(pdf, line[3:].strip(), size=13, style="B")
            pdf.ln(1)
        elif line.startswith("- "):
            _write_wrapped(pdf, f" - {line[2:].strip()}", size=11)
        else:
            _write_wrapped(pdf, line, size=11)

    if fig_path.exists():
        if pdf.get_y() > 130:
            pdf.add_page()
        y = pdf.get_y() + 2
        pdf.image(str(fig_path), x=20, y=y, w=170)
        pdf.set_y(y + 105)
        _write_wrapped(pdf, "Figure: Objective 1 parameter association plot.", size=10, style="I")

    pdf.output(str(pdf_path))
    print(f"[OK] Objective 1 paper pack PDF exported: {pdf_path}")


if __name__ == "__main__":
    main()
